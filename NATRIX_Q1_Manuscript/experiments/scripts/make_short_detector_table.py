"""Build the short-version detector table with the independent char-CNN rows.

The full matched-operating-point table is generated by
``make_revision_tables.py`` from the measured baseline JSON files.  The
short Elsevier version adds the eight character-CNN rows (CSIC and SR-BH,
P1 and P2, full and payload).  This script inserts those rows from the
``learned_*.json`` outputs so the short table is not a manual merge.

Usage
-----
    python experiments/scripts/make_short_detector_table.py
    python experiments/scripts/make_short_detector_table.py --out tables/foo.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

BASE = C.RESULTS / "baselines"
FULL = C.TABLES / "detector_comparison.md"

PREAMBLE = [
    "# Matched operating points: deployment-like (P1) and endpoint-disjoint (P2)",
]

PANELS = {
    "A": "## Panel A: P1 (deployment-like, endpoint may recur)",
    "B": "## Panel B: P2 (endpoint-disjoint, unseen endpoint groups)",
}

CORPUS_KEY = {"CSIC": "csic", "SR-BH": "srbh20k"}


def load_cnn(corpus: str, protocol: str, view: str) -> dict:
    path = BASE / f"learned_{CORPUS_KEY[corpus]}_{protocol}_{view}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    return data["fpr2_crossfit"]


def cnn_row(corpus: str, protocol: str, view: str) -> str:
    m = load_cnn(corpus, protocol, view)
    return (
        f"| {corpus} | CNN-{view} | {100 * m['accuracy']:.2f} | "
        f"{100 * m['fpr']:.2f} | {100 * m['recall']:.2f} | {m['f1']:.4f} |"
    )


def parse_panel(lines: list[str]) -> tuple[list[str], list[str]]:
    """Return (header, data rows) for the first Markdown table in ``lines``."""
    header: list[str] = []
    rows: list[str] = []
    seen = False
    for line in lines:
        if not line.startswith("|"):
            if seen:
                break
            continue
        seen = True
        if len(header) < 2:
            header.append(line)
        else:
            rows.append(line)
    return header, rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(C.TABLES / "detector_comparison_short.md"))
    args = parser.parse_args()

    text = FULL.read_text(encoding="utf-8")
    if "## Panel A" not in text or "## Panel B" not in text:
        raise SystemExit(f"missing panel headings in {FULL}")
    a_start = text.index("## Panel A")
    b_start = text.index("## Panel B")
    panel_a_lines = text[a_start:b_start].splitlines()[1:]
    panel_b_lines = text[b_start:].splitlines()[1:]
    header_a, rows_a = parse_panel(panel_a_lines)
    header_b, rows_b = parse_panel(panel_b_lines)
    if len(header_a) != 2 or len(header_b) != 2:
        raise SystemExit("could not parse the detector tables")

    out: list[str] = list(PREAMBLE) + ["", PANELS["A"], "", *header_a]
    for row in rows_a:
        out.append(row)
        cells = [c.strip() for c in row.strip("|").split("|")]
        corpus, detector = cells[0], cells[1]
        if corpus not in CORPUS_KEY:
            continue
        if detector == "Lex-endpt" or (
            corpus == "SR-BH" and detector == "Lex-payload"
        ):
            out.append(cnn_row(corpus, "P1", "full"))
            out.append(cnn_row(corpus, "P1", "payload"))

    out += ["", PANELS["B"], "", *header_b]
    for row in rows_b:
        out.append(row)
        cells = [c.strip() for c in row.strip("|").split("|")]
        corpus, detector = cells[0], cells[1]
        if corpus in CORPUS_KEY and detector == "Lex-endpt":
            out.append(cnn_row(corpus, "P2", "full"))
            out.append(cnn_row(corpus, "P2", "payload"))

    out_path = Path(args.out)
    out_path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
